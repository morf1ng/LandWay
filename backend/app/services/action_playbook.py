"""Готовые условные шаги логиста по каждому фактору риска (без выдуманных фактов)."""

from __future__ import annotations

import re


def _sid(row: dict) -> str:
    return str(row.get("id") or "груз")


def _problem_label(reason: str) -> str:
    text = reason.strip()
    if text.lower().startswith("синтетическая история"):
        return "Опора на демо-историю коридора"
    if "мало похожих" in text.lower():
        return "Недостаточно похожих рейсов в истории"
    if len(text) > 120:
        return text[:117] + "…"
    return text[0].upper() + text[1:] if text else "Общий риск задержки"


def _match(reason: str, *needles: str) -> bool:
    low = reason.lower()
    return any(n in low for n in needles)


def _solutions(reason: str, row: dict) -> list[str]:
    sid = _sid(row)
    route = row.get("route") or "маршрут"

    if _match(reason, "загружен", "порт"):
        port = re.search(r"порта?\s+(.+)$", reason, re.I)
        port_name = port.group(1).strip() if port else "порта"
        return [
            f"Если выгрузка на {port_name} критична по сроку — заложите +4–8 ч к ETA и согласуйте с получателем перенос окна (текущая оценка: {row.get('estimatedDelay')} ч).",
            f"Если загрузка порта ≥ 60% — откройте раздел «Маршруты» для {sid}: сравните альтернативу через другой порт Каспия без смены статуса ж/д участка.",
            f"Если есть запас по дням — перенесите отправление морского плеча на карточке груза {sid} на следующее доступное окно (демо: симуляция задержки).",
        ]

    if _match(reason, "погод", "неблагоприятн"):
        return [
            "Если ветер ≥ 15 м/с сохраняется 12+ ч — заложите задержку лоцманской проводки (+6–10 ч) и не планируйте узкое окно стыковки в тот же день.",
            f"Если погода улучшается по прогнозу порта — держите экипаж в готовности и зафиксируйте в журнале груза {sid} время фактического выхода судна.",
            "Если риск шторма высокий — в «Маршруты» проверьте обход через сухопутный сегмент к другому порту с более мягкой погодой (только если документы готовы).",
        ]

    if _match(reason, "ветер"):
        return [
            "Если скорость ветра не снизится до < 12 м/с — перенесите морской этап минимум на одно окно (демо: пересчёт прогноза на аналитике).",
            f"Если судно уже стоит под погрузкой — согласуйте по карточке {sid} ожидание в порту вместо выхода в шторм.",
            "Если задержка ж/д плеча растёт — сразу сопоставьте новое время прибытия с расписанием парома; при буфере < 4 ч рассмотрите альтернативный маршрут.",
        ]

    if _match(reason, "поезд", "расписан", "отставан"):
        return [
            f"Если опоздание поезда ≥ 8 ч — обновите ETA получателя и запросите пересчёт прогноза для {sid} (кнопка на аналитике).",
            "Если до парома остаётся менее 4 ч буфера — в «Маршруты» выберите шаблон с более поздним морским рейсом или другим портом отправления.",
            f"Если поезд стабилизировался — зафиксируйте новую ETA в карточке {sid} и снимите лишние предупреждения после пересчёта.",
        ]

    if _match(reason, "пропустить", "морской рейс", "окно пересадки", "пересадк"):
        return [
            f"Если буфер стыковки < 4 ч — приоритет №1: смена морского окна или маршрута для {sid} в разделе «Маршруты».",
            "Если смена рейса недоступна — договоритесь о хранении контейнера в порту и сместите дедлайн доставки на величину ожидаемой задержки.",
            "Если ж/д опоздание продолжает расти — включите сценарий «задержка ж/д» на карточке груза и повторите расчёт риска.",
        ]

    if _match(reason, "документ"):
        return [
            f"Если хотя бы один обязательный документ не «verified» — откройте «Таможня» для {sid} и загрузите/исправьте комплект до выхода судна.",
            "Если статус «ожидает проверки» — назначьте ответственного сверить реквизиты CMR/инвойса и повторить смарт-контракт (демо).",
            "Если до парома < 48 ч — приостановите планирование морского плеча до зелёного статуса документов, чтобы не получить двойную задержку.",
        ]

    if _match(reason, "ожидает отправ", "время", "ограничен"):
        return [
            f"Если груз ещё не в пути к морю — сверьте на карточке {sid} фактическую точку и при необходимости симулируйте задержку ж/д для честного ETA.",
            "Если запас по времени < 24 ч до рейса — минимизируйте параллельные операции: только документы или только смена маршрута, не оба сразу.",
            "Если получатель ждёт жёсткую дату — предложите альтернативу из каталога маршрутов с большим буфером стыковки.",
        ]

    if _match(reason, "истори", "похожих"):
        return [
            f"Для {route}: пересчитайте прогноз после изменения ветра/загрузки порта — число похожих рейсов в демо-истории может вырасти и сменить задержку.",
            "Если режим «только эвристика» — опирайтесь на рекомендацию правил и не трактуйте процент как подтверждённую вероятность перевозчика.",
            "Если нужна воспроизводимая демонстрация — нажмите «Загрузить демо-историю коридора» и снова пересчитайте все грузы.",
        ]

    if _match(reason, "доставка завершена"):
        return [
            "Архивируйте расчёт для отчёта и снимите непрочитанные предупреждения по грузу.",
            "Сверьте фактическое прибытие с планом для накопления истории коридора (в проде — без синтетики).",
            "Передайте получателю итоговый комплект документов из раздела «Таможня».",
        ]

    return [
        f"Если риск остаётся {row.get('riskLevel', 'повышенным')} — откройте карточку {sid} и проверьте активные этапы маршрута «{route}».",
        f"Если задержка > {row.get('estimatedDelay', 0)} ч недопустима — сравните альтернативы в «Маршруты» и пересчитайте прогноз.",
        "Если нужна расшифровка факторов — запустите «Анализ ИИ»: модель переформулирует те же шаги без изменения цифр.",
    ]


def build_action_plans(row: dict) -> list[dict]:
    reasons = list(row.get("reasons") or [])
    if not reasons:
        reasons = ["общий риск задержки по маршруту"]

    seen: set[str] = set()
    plans: list[dict] = []
    for reason in reasons:
        problem = _problem_label(reason)
        key = problem.lower()
        if key in seen:
            continue
        seen.add(key)
        solutions = _solutions(reason, row)
        plans.append({"problem": problem, "solutions": solutions[:3]})

    return plans
